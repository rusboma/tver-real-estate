const property = /недвижим|квартир|жил(ь[ея]|ой|ых|ые|ого|ом)|новостро|застрой|строительств|многоквартир|жкх|коммунал|управляющ.{0,15}компан|капремонт|капитальн.{0,8}ремонт|ипотек|аренд|долев.{0,12}строительств|расселен|аварийн.{0,8}дом|земельн.{0,8}участ|квадратн.{0,8}метр|водоснабжен|теплоснабжен|отопительн|тариф.{0,20}(вод|тепл|газ|электр)/i;
const region = /твер|верхневолж|калининск|торжок|ржев|конаков|кимр|вышн.{0,4}волоч|бежецк/i;
export function relevant(item) {
  const text = `${item.title} ${item.body || ''}`;
  return property.test(text) && region.test(text);
}
