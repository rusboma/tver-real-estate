const theme = /жкх|мкд|управляющ.{0,20}(компан|организац)|жил.{0,15}(дом|комплекс|фонд)|собственник|застройщик|девелопер|коммунал|плат[её]ж|начислен|биллинг|задолжен|дебитор|капремонт|лифт|подъ[её]мн.{0,12}оборуд|уборк|клининг|дворник|благоустрой|домофон|шлагбаум|контрол.{0,15}доступ|пожарн|оповещен|кот[её]л|котельн|теплоснабж|теплов.{0,15}(пункт|насос)|отоплен|вентиляц|энергосбереж|диспетчер|телеметр|сч[её]тчик|умн.{0,10}(дом|город)|водоснабж|водоотвед|гис.?жкх|цифровизац|автоматизац/i;
const promotion = /скидк|распродаж|прайс.?лист|специальн.{0,12}предложен|купите|успейте/i;
const substantive = /внедрен|внедр[яё]|запуск|нов.{0,15}(технолог|систем|решен)|кейс|практик|исследован|вебинар|семинар|конференц|делов.{0,15}программ|форум|выставк|техническ.{0,15}обслужив|модернизац/i;
const foreign = /(?:^|[^а-яё])(в китае|в кнр|в сша|в германии|в дании|в европе|в египте|в украине|в казахстане|европейск.{0,15}рынок|американск.{0,15}рынок)/i;
export function nationalRelevant(item,source={}) {
 const title=item.title||'';const body=item.body||'';
 if(foreign.test(title)&&!/(росси|\bРФ\b)/i.test(title))return false;
 if(promotion.test(title)&&!substantive.test(title))return false;
 if(!theme.test(`${title} ${body}`)&&!(source.sourceType==='national_events'&&substantive.test(title)))return false;
 if(/день рожден|поздравля|юбилей компании|открыли офис|ваканси/i.test(title))return false;
 return true;
}
export function nationalLink(title,source) {
 return nationalRelevant({title},source)||(/семинар|вебинар|форум|выставк|конференц/i.test(title));
}
